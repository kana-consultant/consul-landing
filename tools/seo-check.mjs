#!/usr/bin/env node
/* SEO checks for the static site (P10 SEO E4). No dependencies.

   node tools/seo-check.mjs           check pages + verify sitemap.xml is current
   node tools/seo-check.mjs --write   regenerate sitemap.xml, then check

   Pages: index.html and every <folder>/index.html at the repo root
   (templates/ excluded). Each page must have one <h1>, a canonical URL on
   consul.perfect10.id, valid JSON-LD, and — for sub-pages — a link back to
   the consulting page ("/"). sitemap.xml lists exactly the pages that are NOT
   noindex; lastmod is the page's last git commit date. */
import { readFileSync, writeFileSync, readdirSync, existsSync, statSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const ORIGIN = "https://consul.perfect10.id";
const SKIP = new Set(["templates", "assets", "backend", "tools", "docs", "hermes", "node_modules"]);

function pages() {
  const out = ["index.html"];
  for (const d of readdirSync(ROOT)) {
    if (d.startsWith(".") || SKIP.has(d)) continue;
    const f = join(ROOT, d, "index.html");
    if (statSync(join(ROOT, d)).isDirectory() && existsSync(f)) out.push(`${d}/index.html`);
  }
  return out.sort();
}

function lastmod(file) {
  try {
    const d = execFileSync("git", ["log", "-1", "--format=%cs", "--", file], { cwd: ROOT }).toString().trim();
    if (d) return d;
  } catch {}
  return new Date().toISOString().slice(0, 10); // uncommitted file
}

const errors = [];
const indexable = [];
for (const file of pages()) {
  const html = readFileSync(join(ROOT, file), "utf8");
  const err = (m) => errors.push(`${file}: ${m}`);
  const h1s = html.match(/<h1[\s>]/g) || [];
  if (h1s.length !== 1) err(`expected exactly one <h1>, found ${h1s.length}`);
  const canon = html.match(/<link rel="canonical" href="([^"]+)"/);
  const expected = ORIGIN + "/" + (file === "index.html" ? "" : file.replace(/index\.html$/, ""));
  if (!canon) err("missing rel=canonical");
  else if (canon[1] !== expected) err(`canonical ${canon[1]} should be ${expected}`);
  const lds = [...html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)];
  if (!lds.length) err("missing JSON-LD");
  for (const m of lds) { try { JSON.parse(m[1]); } catch (e) { err(`invalid JSON-LD: ${e.message}`); } }
  if (file !== "index.html" && !/<a href="\/"/.test(html)) err('missing link back to the consulting page (href="/")');
  const robots = (html.match(/<meta name="robots" content="([^"]+)"/) || [])[1] || "";
  if (!/noindex/i.test(robots)) indexable.push({ loc: expected, lastmod: lastmod(file) });
}

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <!-- Generated by tools/seo-check.mjs --write. Indexable pages only:
       pages with <meta name="robots" content="noindex"> stay out. -->
${indexable.map((p) => `  <url>\n    <loc>${p.loc}</loc>\n    <lastmod>${p.lastmod}</lastmod>\n  </url>`).join("\n")}
</urlset>
`;
const smPath = join(ROOT, "sitemap.xml");
if (process.argv.includes("--write")) writeFileSync(smPath, sitemap);
else {
  const cur = existsSync(smPath) ? readFileSync(smPath, "utf8") : "";
  const locs = (x) => [...x.matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1]).sort().join(",");
  if (locs(cur) !== locs(sitemap)) errors.push(`sitemap.xml is out of date (expected: ${locs(sitemap) || "none"}). Run: node tools/seo-check.mjs --write`);
}

if (errors.length) { console.error(errors.map((e) => "✗ " + e).join("\n")); process.exit(1); }
console.log(`✓ ${pages().length} pages OK; sitemap lists ${indexable.length}: ${indexable.map((p) => p.loc).join(", ")}`);
